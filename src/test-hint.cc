#include "hb.hh"

#include "OT/glyf/glyf.hh"
#include "OT/glyf/hinter.hh"

#ifdef HAVE_FREETYPE
#include <ft2build.h>
#include FT_FREETYPE_H
#endif

#include <math.h>
#include <stdio.h>

/*
 * The font is generated by test/api/generate-hint-minimal-font.py.  Glyph 1
 * is a 200x200 square with this program:
 *
 *   SVTCA[y]     projection and freedom vectors to the y axis
 *   PUSHB[0] 2   point index 2
 *   MDAP[1]      move point 2 to the rounded y grid line
 *
 * At 16 ppem / 1000 upem point 2 is scaled to 3.2 pixels; MDAP rounds it to
 * 3 pixels, which is 187.5 font units.
 */

#ifdef HAVE_FREETYPE

static int32_t
scale_for_ppem (unsigned ppem, unsigned upem)
{
  return (int32_t) (((int64_t) ppem * OT::glyf_impl::F26DOT6_ONE *
		     OT::glyf_impl::F16DOT16_ONE) /
		    upem);
}

/* Convert font units written back by hint_glyph() to 26.6 device space. */
static int32_t
to_26_6 (float v, int32_t scale)
{ return (int32_t) roundf (v * scale / (float) OT::glyf_impl::F16DOT16_ONE); }

static void
compare_outline (FT_Face ft_face,
		 hb_codepoint_t gid,
		 const contour_point_vector_t &points,
		 unsigned ppem,
		 unsigned upem,
		 FT_Int32 load_flags,
		 const char *label)
{
  hb_always_assert (FT_Load_Glyph (ft_face, gid, load_flags) == 0);
  hb_always_assert (ft_face->glyph->format == FT_GLYPH_FORMAT_OUTLINE);

  const FT_Outline &outline = ft_face->glyph->outline;
  unsigned count = points.length - OT::glyf_impl::PHANTOM_COUNT;
  hb_always_assert ((unsigned) outline.n_points == count);

  int32_t scale = scale_for_ppem (ppem, upem);
  for (unsigned i = 0; i < count; i++)
  {
    int32_t hb_x = to_26_6 (points[i].x, scale);
    int32_t hb_y = to_26_6 (points[i].y, scale);
    int32_t ft_x = (int32_t) outline.points[i].x;
    int32_t ft_y = (int32_t) outline.points[i].y;

    if (hb_x != ft_x || hb_y != ft_y)
      fprintf (stderr, "test-hint: %s point %u: hb=(%d,%d) ft=(%d,%d)\n", label,
	       i, hb_x, hb_y, ft_x, ft_y);

    hb_always_assert (hb_x == ft_x);
    hb_always_assert (hb_y == ft_y);
  }

  /* The hinted advance comes from the right/left phantom points. */
  unsigned first_phantom = points.length - OT::glyf_impl::PHANTOM_COUNT;
  int32_t hb_advance =
      to_26_6 (points[first_phantom + OT::glyf_impl::PHANTOM_RIGHT].x -
		   points[first_phantom + OT::glyf_impl::PHANTOM_LEFT].x,
	       scale);
  hb_always_assert (hb_advance == (int32_t) ft_face->glyph->advance.x);

  printf ("test-hint: %s points and advance match FreeType (%u points)\n",
	  label, count);
}

#endif /* HAVE_FREETYPE */

int
main (int argc, char **argv)
{
  hb_always_assert (argc == 2);

  hb_blob_t *blob = hb_blob_create_from_file (argv[1]);
  hb_always_assert (blob);
  hb_face_t *face = hb_face_create (blob, 0);
  hb_font_t *font = hb_font_create (face);
  hb_font_set_ppem (font, 16, 16);

  OT::glyf_accelerator_t glyf (face);
  auto glyph = glyf.glyph_for_gid (1);
  hb_always_assert (glyph.get_type () == OT::glyf_impl::Glyph::SIMPLE);

  contour_point_vector_t points;
  hb_always_assert (glyph.get_all_points_without_var (face, points));
  /* Four outline points plus four phantom points. */
  hb_always_assert (points.length == 8);
  hb_always_assert (points[2].x == 200.f);
  hb_always_assert (points[2].y == 200.f);
  hb_always_assert (points[3].is_end_point);

  /* Keep the pre-hinting points; FreeType can validate our scaling too. */
  contour_point_vector_t unhinted_points;
  hb_always_assert (unhinted_points.resize (points.length));
  for (unsigned i = 0; i < points.length; i++) unhinted_points[i] = points[i];

  OT::glyf_impl::hinter_t hinter (font);
  hb_always_assert (hinter.hint_glyph (1, points));

  /* Point 2 moved from 3.2px to 3.0px. */
  hb_always_assert (fabsf (points[2].y - 187.5f) < 0.01f);
  /* MDAP moved it along y only. */
  hb_always_assert (points[2].x == 200.f);
  /* Untouched points stay put; IUP is an explicit instruction. */
  hb_always_assert (points[0].y == 0.f);
  hb_always_assert (points[1].y == 0.f);
  hb_always_assert (points[3].y == 200.f);

#ifdef HAVE_FREETYPE
  FT_Library ft_library = nullptr;
  FT_Face ft_face = nullptr;
  hb_always_assert (FT_Init_FreeType (&ft_library) == 0);
  hb_always_assert (FT_New_Face (ft_library, argv[1], 0, &ft_face) == 0);
  hb_always_assert (FT_Set_Pixel_Sizes (ft_face, 16, 16) == 0);

  unsigned upem = hb_face_get_upem (face);
  compare_outline (ft_face, 1, unhinted_points, 16, upem,
		   FT_LOAD_NO_HINTING | FT_LOAD_NO_BITMAP, "unhinted");
  compare_outline (ft_face, 1, points, 16, upem,
		   FT_LOAD_NO_AUTOHINT | FT_LOAD_NO_BITMAP |
		       FT_LOAD_TARGET_NORMAL,
		   "hinted");

  FT_Done_Face (ft_face);
  FT_Done_FreeType (ft_library);
#else
  printf ("test-hint: FreeType comparison skipped (not built)\n");
#endif

  hb_font_destroy (font);
  hb_face_destroy (face);
  hb_blob_destroy (blob);

  printf ("test-hint: ok\n");
  return 0;
}
